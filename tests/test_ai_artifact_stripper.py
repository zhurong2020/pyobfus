# Marker pattern coverage
# --------------------------------------------------------------------------- #


@pytest.mark.parametrize(
    "marker",
    [
        "Generated by Claude",
        "generated with copilot",
        "Generated by ChatGPT",
        "Generated by GPT",
        "Co-Authored-By: Claude",
        "Coauthored by AI",
        "written by Cursor",
        "made with Gemini",
        "This uses Claude Code under the hood",
        "\U0001f916 Generated with something",
    ],
)
def test_marker_variants_detected(marker):
    tree, t = _strip(f'def f():\n    "{marker}"\n    return 1\n')
    assert t.get_statistics()["docstrings_stripped"] == 1
    assert _run(tree)["f"]() == 1


# --------------------------------------------------------------------------- #
# Must NOT remove legitimate content
# --------------------------------------------------------------------------- #


def test_legit_docstring_preserved():
    src = 'def add(a, b):\n    "Return the sum of a and b."\n    return a + b\n'
    tree, t = _strip(src)
    assert "Return the sum of a and b." in _strings_in(tree)
    assert t.get_statistics()["docstrings_stripped"] == 0
    assert _run(tree)["add"](2, 3) == 5


def test_legit_author_dunder_preserved():
    tree, t = _strip('__author__ = "Jane Doe"\nx = 1')
    ns = _run(tree)
    assert ns["__author__"] == "Jane Doe"
    assert t.get_statistics()["attributions_stripped"] == 0


def test_arbitrary_string_literal_not_touched():
    """A regular (non-dunder) assignment is data, not metadata — leave it."""
    tree, t = _strip('note = "Generated by Claude"\nresult = note.upper()')
    ns = _run(tree)
    assert ns["note"] == "Generated by Claude"
    assert ns["result"] == "GENERATED BY CLAUDE"
    assert t.get_statistics()["attributions_stripped"] == 0
    assert t.get_statistics()["docstrings_stripped"] == 0


def test_marker_inside_print_call_not_touched():
    tree, _ = _strip('def show():\n    return "Generated by Claude"\n')
    # the return value is program data, must survive
    assert _run(tree)["show"]() == "Generated by Claude"


def test_disabled_by_default_is_noop():
    src = '"""\U0001f916 Generated with Claude Code."""\n__author__ = "Generated by Claude"\nx = 1'
    tree, t = _strip(src, enabled=False)
    ns = _run(tree)
    assert ns["__author__"] == "Generated by Claude"
    assert t.get_statistics()["docstrings_stripped"] == 0
    assert t.get_statistics()["attributions_stripped"] == 0


