def test_author_dunder_with_marker_removed():
    tree, t = _strip('__author__ = "Generated by Claude"\nx = 5')
    ns = _run(tree)
    assert "__author__" not in ns
    assert ns["x"] == 5
    assert t.get_statistics()["attributions_stripped"] == 1


@pytest.mark.parametrize(
    "dunder", ["__copyright__", "__credits__", "__maintainer__", "__authors__"]
)
def test_other_attribution_dunders_removed(dunder):
    tree, t = _strip(f'{dunder} = "made with cursor"\nkeep = 1')
    ns = _run(tree)
    assert dunder not in ns
    assert ns["keep"] == 1


def test_annotated_author_dunder_removed():
    tree, t = _strip('__author__: str = "written by Copilot"\nx = 1')
    ns = _run(tree)
    assert "__author__" not in ns
    assert ns["x"] == 1
    assert t.get_statistics()["attributions_stripped"] == 1


