"""
Tests for the Community AI artifact stripper.

Verifies that AI provenance markers are removed from docstrings and attribution
dunders, that legitimate documentation / data is left intact, and that stripped
code still compiles and runs. Tests compile+exec the transformed AST directly,
so they run identically on Python 3.8-3.14.
"""

import ast

import pytest

from pyobfus.config import ObfuscationConfig
from pyobfus.transformers.ai_artifact_stripper import AIArtifactStripper


def _strip(source: str, enabled: bool = True):
    """Transform source, return (new_tree, transformer)."""
    config = ObfuscationConfig.community_edition()
    config.strip_ai_artifacts = enabled
    tree = ast.parse(source)
    transformer = AIArtifactStripper(config)
    new_tree = transformer.transform(tree)
    return new_tree, transformer


def _strings_in(tree: ast.AST):
    """All str constants present in the tree (for assertion convenience)."""
    return [
        n.value for n in ast.walk(tree) if isinstance(n, ast.Constant) and isinstance(n.value, str)
    ]


def _run(tree: ast.AST) -> dict:
    code = compile(tree, "<strip>", "exec")
    ns: dict = {}
    exec(code, ns)  # noqa: S102 - executing our own transformed AST in tests
    return ns


# --------------------------------------------------------------------------- #
# Docstring removal
# --------------------------------------------------------------------------- #


def test_module_docstring_with_marker_removed():
    tree, t = _strip('"""Module.\n\n\U0001f916 Generated with Claude Code.\n"""\nx = 1')
    assert all("Generated with Claude" not in s for s in _strings_in(tree))
    assert t.get_statistics()["docstrings_stripped"] == 1
    assert _run(tree)["x"] == 1


def test_function_docstring_with_marker_removed_body_preserved():
    src = "def f():\n" '    "Fetch a user. Generated by Claude."\n' "    return 42\n"
    tree, t = _strip(src)
    assert all("Generated by Claude" not in s for s in _strings_in(tree))
    assert t.get_statistics()["docstrings_stripped"] == 1
    assert _run(tree)["f"]() == 42


def test_function_with_only_ai_docstring_gets_pass():
    """If removing the docstring empties the body, a `pass` is inserted."""
    tree, _ = _strip('def f():\n    "Generated by Copilot."\n')
    func = tree.body[0]
    assert isinstance(func, ast.FunctionDef)
    assert len(func.body) == 1
    assert isinstance(func.body[0], ast.Pass)
    # still callable
    assert _run(tree)["f"]() is None


def test_class_docstring_with_marker_removed():
    src = 'class C:\n    "Service. Co-Authored-By: Claude"\n    value = 7\n'
    tree, t = _strip(src)
    assert all("Co-Authored-By" not in s for s in _strings_in(tree))
    assert t.get_statistics()["docstrings_stripped"] == 1
    assert _run(tree)["C"].value == 7


