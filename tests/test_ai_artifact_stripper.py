def test_realistic_module_round_trip():
    src = (
        '"""User service.\n\n\U0001f916 Generated with Claude Code. Here is the implementation.\n"""\n'
        '__author__ = "Generated by Claude"\n'
        '__version__ = "1.0"\n'
        "\n"
        "def get_user(uid):\n"
        '    "Fetch a user by id. Generated by Claude."\n'
        "    label = 'AI-generated stub'\n"
        "    return {'id': uid, 'note': label}\n"
    )
    tree, t = _strip(src)
    ns = _run(tree)

    # AI markers gone from docstrings + dunders
    assert "__author__" not in ns
    assert ns["__version__"] == "1.0"  # legit dunder kept
    # arbitrary string data preserved
    assert ns["get_user"](9) == {"id": 9, "note": "AI-generated stub"}

    stats = t.get_statistics()
    assert stats["docstrings_stripped"] == 2  # module + function
    assert stats["attributions_stripped"] == 1  # __author__


def test_statistics_shape():
    tree, t = _strip('def f():\n    "Generated by Claude"\n    return 1\n')
    stats = t.get_statistics()
    assert set(stats) == {"docstrings_stripped", "attributions_stripped", "transformations"}
    assert stats["transformations"] == 1
