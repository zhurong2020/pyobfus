"""
Single source of truth for pyobfus.yaml's configuration schema.

Derived from ObfuscationConfig's actual dataclass fields
(dataclasses.fields()) so the set of recognized keys can never silently
drift out of sync with the config it describes. Found 2026-08-06:
config_validator.py's old hand-maintained VALID_SCHEMA dict had drifted
stale -- missing `preset` (the key `pyobfus --init` itself writes into
every config it generates) and every Pro field added since v0.5.0 --
producing false "Unknown configuration key" warnings on --init's own
output. See docs/VSCODE_EXTENSION_PLAN.md's M3 section for the full
investigation.

Two consumers:
- pyobfus.config_validator (CLI `--validate-config`) calls describe_fields()
  live, every call -- there's no cached/generated artifact for this
  consumer to go stale.
- scripts/generate_vscode_schema.py (release-time, not a runtime
  dependency of this package) walks the same data to emit a standard JSON
  Schema file for the VS Code extension's `pyobfus.yaml` IntelliSense.
"""

