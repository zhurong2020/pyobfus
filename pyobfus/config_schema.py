def _resolve_field_default(default: Any, default_factory: Any) -> Any:
    if default is not MISSING:
        return default
    if default_factory is not MISSING:
        return default_factory()
    return None


def _json_type_for(python_type: Any) -> Dict[str, Any]:
    """
    Map a dataclass field's type annotation to a (json_type, item_type)
    pair. Handles the concrete shapes ObfuscationConfig actually uses:
    str, bool, int, List[str], Set[str], Optional[str], Optional[int].
    Anything unrecognized degrades to a generic "string" rather than
    raising -- a new field with an unmapped type still gets a schema
    entry (fixing the actual bug this module exists for), just a less
    precise one, instead of silently vanishing again.
    """
    origin = get_origin(python_type)

    if python_type is bool:
        return {"json_type": "boolean"}
    if python_type is str:
        return {"json_type": "string"}
    if python_type is int:
        return {"json_type": "integer"}

    if origin is list or origin is set:
        (item_type,) = get_args(python_type) or (str,)
        return {"json_type": "array", "item_type": _json_type_for(item_type)["json_type"]}

    if origin is Union:
        args = [a for a in get_args(python_type) if a is not type(None)]
        if len(args) == 1:
            inner = _json_type_for(args[0])
            inner["nullable"] = True
            return inner

    # Fallback: unrecognized annotation shape.
    return {"json_type": "string"}


def describe_fields() -> List[Dict[str, Any]]:
    """
    Introspect ObfuscationConfig's actual dataclass fields and return
    structured metadata for each: name, json_type, item_type (for arrays),
    nullable, default (JSON-safe), description, pro_only, valid_values
    (only set for `level`).

    This is the single source of truth for "what keys does pyobfus.yaml's
    `obfuscation:` section accept" -- every consumer should derive from
    this rather than hand-maintaining its own copy.
    """
    described: List[Dict[str, Any]] = []
    for f in fields(ObfuscationConfig):
        default = _resolve_field_default(f.default, f.default_factory)
        if isinstance(default, set):
            default = sorted(default)

        entry: Dict[str, Any] = {
            "name": f.name,
            "default": default,
            "description": _FIELD_DESCRIPTIONS.get(
                f.name, f"{f.name} (see pyobfus.config.ObfuscationConfig)."
            ),
            "pro_only": f.name in _PRO_ONLY_FIELDS,
        }
        entry.update(_json_type_for(f.type))
        if f.name == "level":
            entry["valid_values"] = _LEVEL_VALUES
        if f.name in _MIN_VALUES:
            entry["min_value"] = _MIN_VALUES[f.name]
        described.append(entry)
    return described


def preset_names() -> List[str]:
    """Available top-level `preset:` values, from ObfuscationConfig.list_presets()."""
    return ObfuscationConfig.list_presets()
