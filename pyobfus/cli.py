def _handle_init(scan_root: Path, json_output: bool = False) -> None:
    """
    Scan a project and write a suggested `pyobfus.yaml`.

    When `--json` is set, emits a structured payload on stdout and exits
    without asking for confirmation (overwrites existing file). The JSON
    mode is intended for AI agents and CI pipelines.
    """
    from pyobfus.core.init_config import build_init_result

    result = build_init_result(scan_root)
    target = result.config_path

    if target.exists() and not json_output:
        if not click.confirm(f"'{target}' already exists. Overwrite?"):
            click.echo("Aborted.")
            return

    target.write_text(result.yaml_text, encoding="utf-8")
    result.written = True

    if json_output:
        payload = result.to_dict()
        payload["status"] = "success"
        # Context-aware next-step for AI agents
        if result.high_risk_findings > 0:
            payload["ai_hint"] = (
                f"Generated {target}. "
                f"{result.high_risk_findings} high-risk pattern(s) detected — "
                f"run 'pyobfus --check {scan_root}' for details before obfuscating."
            )
        else:
            payload["ai_hint"] = (
                f"Generated {target}. Next: pyobfus {scan_root} -o dist/ -c {target}"
            )
        click.echo(json.dumps(payload, indent=2, ensure_ascii=False))
        return

    click.echo(f"Generated {target}")
    click.echo(f"  Preset: {result.preset}")
    if result.frameworks_detected:
        click.echo(f"  Frameworks detected: {', '.join(result.frameworks_detected)}")
    click.echo(f"  Files scanned: {result.files_scanned}")
    click.echo(f"  Exclude patterns: {len(result.excludes)} entries")
    if result.high_risk_findings > 0:
        click.echo(
            f"  Warning: {result.high_risk_findings} high-risk pattern(s) detected. "
            f"Run 'pyobfus --check {scan_root}' for details."
        )
    click.echo("")
    click.echo("Next steps:")
    click.echo(f"  1. Review {target}")
    click.echo(f"  2. Run: pyobfus {scan_root} -o dist/ -c {target}")


def _handle_unmap(
    trace_path: Optional[str],
    mapping_path: Optional[str],
    json_output: bool = False,
) -> None:
    """
    Reverse obfuscated identifiers in a stack trace / error log.

    Reads text from `trace_path` (or stdin when `-`) and substitutes every
    known obfuscated identifier with its original name, using a mapping.json
    produced by --save-mapping. Prints the rewritten text to stdout.
    """
    from pyobfus.core.mapping import ObfuscationMapping

    if not mapping_path:
        click.echo("Error: --unmap requires --mapping PATH.", err=True)
        click.echo("Example: pyobfus --unmap --trace error.log --mapping mapping.json", err=True)
        sys.exit(2)

    try:
        mapping = ObfuscationMapping.load(Path(mapping_path))
    except FileNotFoundError as e:
        click.echo(f"Error: {e}", err=True)
        sys.exit(2)
    except (ValueError, json.JSONDecodeError) as e:  # noqa: F821 — json imported below
        click.echo(f"Error: invalid mapping file: {e}", err=True)
        sys.exit(2)

    if trace_path in (None, "-"):
        trace_text = sys.stdin.read()
    else:
        trace_file = Path(trace_path)  # type: ignore[arg-type]
        if not trace_file.exists():
            click.echo(f"Error: trace file not found: {trace_path}", err=True)
            sys.exit(2)
        trace_text = trace_file.read_text(encoding="utf-8")

    if not trace_text.strip():
        click.echo("Error: no trace input (empty file or stdin).", err=True)
        sys.exit(2)

    rewritten = mapping.unmap_text(trace_text)

    if json_output:
        click.echo(
            json.dumps(
                {
                    "version": 1,
                    "mapping": str(mapping_path),
                    "mapping_stats": mapping.stats(),
                    "original_trace": trace_text,
                    "unmapped_trace": rewritten,
                    "ai_hint": (
                        "Unmapped names use the pre-obfuscation identifiers; "
                        "line numbers still refer to the obfuscated output."
                    ),
                },
                indent=2,
                ensure_ascii=False,
            )
        )
    else:
        click.echo(rewritten, nl=False)


def _handle_check(input_path: Path, json_output: bool = False) -> None:
    """
    Run pre-flight risk scan and print report.

    Exits with code 0 (safe), 1 (high-severity findings), or 2 (parse errors).
    """
    from pyobfus.core.preflight import PreflightChecker, format_report_text

    checker = PreflightChecker()
    report = checker.check_path(input_path)

    if json_output:
        click.echo(report.to_json())
    else:
        click.echo(format_report_text(report))

    sys.exit(report.exit_code())


def _handle_validate_config(config_path: str) -> None:
    """
    Validate a configuration file and report errors/warnings.

    Args:
        config_path: Path to configuration file
    """
    click.echo(f"Validating: {config_path}\n")

    result = validate_config_file(Path(config_path))

    # Print errors
    for error in result.errors:
        click.echo(error, err=True)

    # Print warnings
    for warning in result.warnings:
        click.echo(warning)

    # Print suggestions
    for suggestion in result.suggestions:
        click.echo(suggestion)

    # Print summary
    click.echo(f"\n{result.get_summary()}")

    if not result.is_valid:
        sys.exit(1)


