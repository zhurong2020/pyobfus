"""File-scoped v2 traceback restoration; no inferred whole-text context."""

from __future__ import annotations

import re
import unicodedata
from typing import TYPE_CHECKING, Any, Dict, List, Set, Tuple

from pyobfus.core.mapping import _path_parts, _unicode_identifiers

if TYPE_CHECKING:
    from pyobfus.core.mapping import ObfuscationMapping

_FRAME = re.compile(
    r'^(?P<indent>[ \t|]*)File "(?P<path>[^"\r\n]+)", line (?P<line>[0-9]+), in (?P<name>[^\r\n]+)$'
)
_MARKER = re.compile(r"^[ \t|]*# pyobfus:obfuscated id=(\S+)", re.MULTILINE)
_RESTORED = re.compile(
    r"  \[(?:obfuscated: [^\r\n]+:[0-9]+|generated by pyobfus|names restored by pyobfus)\]$"
)
Root = Tuple[bool, Tuple[str, ...]]


def restore_independent_trace(mapping: ObfuscationMapping, trace: str) -> Dict[str, Any]:
    """Require one root consistent with every frame carrying file/name evidence.

    Use all suffix candidates jointly, not the longest suffix or a majority
    vote: a deployment directory can share a name with a nested package.
    """
    markers = {value.lower() for value in _MARKER.findall(trace)}
    mismatch = bool(markers and markers != {mapping.marker_id()})
    candidates: List[Tuple[str, str, Any, Dict[Root, List[str]]]] = []
    named_sets: List[Set[Root]] = []
    path_sets: List[Set[Root]] = []
    for text in trace.splitlines(keepends=True):
        body = text.rstrip("\r\n")
        ending = text[len(body) :]
        match = _FRAME.fullmatch(body)
        if match is not None and _RESTORED.search(match["name"]):
            match = None
        matches: Dict[Root, List[str]] = {}
        if match is None:
            candidates.append((body, ending, None, matches))
            continue
        parts = _path_parts(match["path"])
        named: Set[Root] = set()
        tokens = {
            unicodedata.normalize("NFKC", name)
            for _, _, name in _unicode_identifiers(match["name"])
        }
        for key in set(mapping.file_names) | set(mapping.unmapped_files):
            names = {} if key in mapping.unmapped_files else mapping.file_names.get(key, {})
            suffix = _path_parts(key)
            if len(parts) < len(suffix) or parts[-len(suffix) :] != suffix:
                continue
            candidate_root = (match["path"].startswith(("/", "\\")), tuple(parts[: -len(suffix)]))
            matches.setdefault(candidate_root, []).append(key)
            if any(len(names.get(token, [])) == 1 for token in tokens):
                named.add(candidate_root)
        candidates.append((body, ending, match, matches))
        if matches:
            path_sets.append(set(matches))
        if named:
            # A failed/stale colliding file has no name table. Its absence is
            # not evidence that a shorter successful suffix owns the frame.
            named.update(
                candidate
                for candidate, keys in matches.items()
                if any(key in mapping.unmapped_files for key in keys)
            )
            named_sets.append(named)

    # Path-only frames can contradict a foreign short-name match. Every known
    # path participates, even if this conservatively declines stdlib collisions.
    evidence = path_sets + named_sets
    roots = set.intersection(*evidence) if evidence else set()
    root = next(iter(roots)) if len(roots) == 1 and not mismatch else None
    if root is not None and not named_sets and not markers:
        corroborating_keys = {
            key
            for _, _, _, matches in candidates
            for key in matches.get(root, [])
            if key in mapping.file_names
        }
        if len(corroborating_keys) < 2:
            root = None
    frames: List[Dict[str, Any]] = []
    output: List[str] = []
    for body, ending, match, matches in candidates:
        if match is None:
            output.append(body + ending)
            continue
        keys = matches.get(root, []) if root is not None else []
        output_key = keys[0] if len(keys) == 1 else None
        line = int(match["line"])
        record = mapping.files.get(output_key) if output_key is not None else None
        accepted = (
            record is not None
            and output_key not in mapping.unmapped_files
            and 1 <= line <= record["line_count"]
        )
        location = (
            mapping.resolve_file_location(output_key, line)
            if output_key is not None and accepted
            else None
        )
        status = location.status if location else "unmapped"
        frames.append(
            {
                "obfuscated_file": match["path"],
                "obfuscated_line": line,
                "original_file": location.source if location and status == "mapped" else None,
                "original_line": location.line if location and status == "mapped" else None,
                "status": status,
                "resolved_file": output_key if accepted else None,
            }
        )
        if output_key is not None and accepted:
            name = mapping.unmap_file_text(match["name"], output_key)
            if status == "mapped":
                assert location is not None
                body = (
                    f'{match["indent"]}File "{location.source}", line {location.line}, in {name}'
                    f'  [obfuscated: {match["path"]}:{line}]'
                )
            else:
                body = f'{match["indent"]}File "{match["path"]}", line {line}, in {name}'
                if status == "generated":
                    body += "  [generated by pyobfus]"
                elif name != match["name"]:
                    body += "  [names restored by pyobfus]"
        output.append(body + ending)

    usable = [record.get("lines") is not None for record in mapping.files.values()]
    line_map = "absent"
    if any(usable):
        line_map = (
            "available"
            if all(usable) and frames and all(frame["status"] != "unmapped" for frame in frames)
            else "partial"
        )
    hint = (
        "Independent-file mapping restores frame names only for a uniquely resolved file and "
        "deployment root. Ambiguous names and unknown/out-of-range frames stay unchanged. "
        "All matching path evidence must agree, including path-only frames; otherwise nothing "
        "is inferred from a majority. Path-only restoration needs a supplied matching marker "
        "or at least two distinct file keys. "
        "Source excerpts, exception messages, unframed logs and caret columns retain artifact "
        "text; they are not rewritten using the last frame. Mapped locations have statement-level "
        "precision; unavailable line tables retain output locations."
    )
    if mismatch:
        hint += (
            " Trace marker mismatch: no names or locations were restored; use the matching mapping."
        )
    elif not markers:
        hint += " No trace marker supplied: build identity is unverified."
    else:
        hint += " Supplied marker matches the mapping id; this is not an authentication check."
    if evidence and len(roots) != 1:
        hint += " Deployment root is ambiguous or inconsistent; frames remain unresolved."
    if not frames:
        hint += " No recognized traceback frames: no names were restored."
    if mapping.unmapped_files:
        hint += " Some outputs were not mapped in this build; their paths are excluded from restoration."
    return {
        "unmapped_trace": "".join(output),
        "frames": frames,
        "line_map": line_map,
        "ai_hint": hint,
    }
